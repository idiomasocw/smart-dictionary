-- Status enum for the JIT Dictionary Builder cron jobs
CREATE TYPE word_status AS ENUM ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED');

-- Status enum for the Background Video Processing pipeline
CREATE TYPE video_status AS ENUM ('UPLOADED', 'AUDIO_EXTRACTED', 'TRANSCRIBED', 'PROCESSED', 'FAILED');

-- Stores the supported languages (e.g., 'en', 'es', 'fr', 'de', 'pt', 'it')
CREATE TABLE languages (
    code VARCHAR(2) PRIMARY KEY, -- e.g., 'en'
    name VARCHAR(50) NOT NULL    -- e.g., 'English'
);

-- The Root Words table (Lemmas only, filtered by spaCy)
CREATE TABLE words (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    lemma VARCHAR(255) NOT NULL,
    language_code VARCHAR(2) NOT NULL REFERENCES languages(code) ON DELETE CASCADE,
    
    -- The State Machine for the Cron Dispatcher
    status word_status DEFAULT 'PENDING',
    
    -- AI-Generated array of conjugations/plurals (e.g., ["ate", "eating", "eaten"])
    -- Storing this as JSONB allows lightning-fast indexing and searching
    conjugations JSONB DEFAULT '[]'::jsonb, 
    
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    
    -- Crucial: Prevents duplicate seed entries for the same language
    UNIQUE(lemma, language_code)
);

-- The Definitions table (One word can have multiple meanings/parts of speech)
CREATE TABLE definitions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    word_id UUID NOT NULL REFERENCES words(id) ON DELETE CASCADE,
    
    part_of_speech VARCHAR(50) NOT NULL, -- e.g., 'noun', 'verb'
    cefr_level VARCHAR(2),               -- e.g., 'A1', 'B2', 'C1'
    
    -- The actual definition in the target language
    meaning TEXT NOT NULL,
    
    -- Translations stored as a key-value JSON object for multiple native languages
    -- e.g., {"es": "banco", "fr": "banque", "de": "Bank"}
    translations JSONB NOT NULL DEFAULT '{}'::jsonb,
    
    -- JIT Audio generation tracking (ElevenLabs)
    audio_s3_url TEXT,
    
    created_at TIMESTAMPTZ DEFAULT NOW(),
    
    -- Ensuring we don't accidentally duplicate the exact same meaning for a word
    UNIQUE(word_id, part_of_speech, meaning)
);

-- Text examples generated by the AI for a specific definition
CREATE TABLE text_examples (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    definition_id UUID NOT NULL REFERENCES definitions(id) ON DELETE CASCADE,
    example_text TEXT NOT NULL,
    
    -- Translations of the example sentence
    translations JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- Tracks the long, raw videos uploaded by your team
CREATE TABLE source_videos (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    title VARCHAR(255) NOT NULL,
    language_code VARCHAR(2) NOT NULL REFERENCES languages(code),
    
    -- S3 references
    s3_raw_video_url TEXT NOT NULL,
    s3_extracted_audio_url TEXT, -- Populated after Ampere worker extracts audio
    
    -- Pipeline state
    status video_status DEFAULT 'UPLOADED',
    
    -- The raw Deepgram JSON output with word-level timestamps can be stored in S3 
    -- and linked here, or stored directly if it's not too massive.
    transcript_s3_url TEXT, 
    
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- The final extracted clips, mapped to semantic meaning
CREATE TABLE video_clips (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    source_video_id UUID NOT NULL REFERENCES source_videos(id) ON DELETE CASCADE,
    
    -- THE MOST IMPORTANT LINK: Ties the clip to the exact semantic meaning, not just the word
    definition_id UUID NOT NULL REFERENCES definitions(id) ON DELETE CASCADE,
    
    -- The final public CDN URL
    s3_clip_url TEXT NOT NULL,
    
    -- Metadata for the player and AI verification
    start_time NUMERIC(10, 3) NOT NULL, -- e.g., 14.500 seconds
    end_time NUMERIC(10, 3) NOT NULL,   -- e.g., 18.250 seconds
    transcript_text TEXT NOT NULL,      -- The specific sentence being spoken
    
    -- How confident the LLM was that this clip matches the definition meaning
    ai_confidence_score NUMERIC(3, 2) CHECK (ai_confidence_score >= 0 AND ai_confidence_score <= 1),
    
    created_at TIMESTAMPTZ DEFAULT NOW()
);

